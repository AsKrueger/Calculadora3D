package com.tdcostmanager.app.core.importer

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.math.BigDecimal
import java.util.Base64
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

class SliceParserTest {

    @Test
    fun `duraciones en todos los formatos`() {
        assertEquals(93784L, SliceParser.parseDuration("1d 2h 3m 4s"))
        assertEquals(7500L, SliceParser.parseDuration("2h 5m"))
        assertEquals(2710L, SliceParser.parseDuration("45m 10s"))
        assertEquals(3723L, SliceParser.parseDuration("01:02:03"))
        assertEquals(3725L, SliceParser.parseDuration("3725"))
        assertNull(SliceParser.parseDuration("pronto"))
    }

    @Test
    fun `G-code de Orca, Flash Studio o PrusaSlicer con dos filamentos`() {
        val gcode = """
            ; generated by OrcaSlicer 2.2.0
            G28
            G1 X10 Y10
            ; filament used [mm] = 3720.11, 410.20
            ; filament used [g] = 11.09, 1.22
            ; total filament used [g] = 12.31
            ; estimated printing time (normal mode) = 1h 23m 5s
            ; filament_type = PLA;PETG
            ; filament_colour = #FF0000;#00FF00
        """.trimIndent()
        val info = SliceParser.parseGcode(gcode)
        assertEquals(4985L, info.printSeconds)
        assertEquals(2, info.filaments.size)
        assertEquals(BigDecimal("11.09"), info.filaments[0].grams)
        assertEquals("PLA", info.filaments[0].type)
        assertEquals("#00FF00", info.filaments[1].colorHex)
    }

    @Test
    fun `G-code de Bambu Studio con cabecera`() {
        val gcode = """
            ; HEADER_BLOCK_START
            ; model printing time: 52m 10s; total estimated time: 58m 31s
            ; total filament weight [g] : 20.43
            ; HEADER_BLOCK_END
        """.trimIndent()
        val info = SliceParser.parseGcode(gcode)
        assertEquals(3511L, info.printSeconds)
        assertEquals(BigDecimal("20.43"), info.filaments.single().grams)
    }

    @Test
    fun `G-code de Cura en metros`() {
        val gcode = ";FLAVOR:Marlin\n;TIME:6122\n;Filament used: 4.37526m\n;Layer height: 0.2\nG28"
        val info = SliceParser.parseGcode(gcode)
        assertEquals(6122L, info.printSeconds)
        assertEquals(BigDecimal("4.37526"), info.filaments.single().meters)
    }

    @Test
    fun `extrae la miniatura mas grande`() {
        val small = byteArrayOf(1, 2, 3)
        val big = byteArrayOf(9, 8, 7, 6, 5)
        fun block(w: Int, bytes: ByteArray) =
            "; thumbnail begin ${w}x$w ${bytes.size}\n; ${Base64.getEncoder().encodeToString(bytes)}\n; thumbnail end\n"
        val gcode = block(16, small) + block(300, big) + "; estimated printing time (normal mode) = 10m\n"
        assertArrayEquals(big, SliceParser.parseGcode(gcode).thumbnail)
    }

    @Test
    fun `3MF laminado de Bambu u Orca con dos placas`() {
        val xml = """
            <config>
              <plate>
                <metadata key="index" value="1"/>
                <metadata key="prediction" value="3600"/>
                <metadata key="weight" value="30.5"/>
                <filament id="1" type="PLA" color="#000000" used_m="9.1" used_g="27.3" />
                <filament id="2" type="PLA" color="#FFFFFF" used_m="1.0" used_g="3.2" />
              </plate>
              <plate>
                <metadata key="prediction" value="1800"/>
                <filament id="1" type="PLA" color="#000000" used_m="3.0" used_g="9.0" />
              </plate>
            </config>
        """.trimIndent()
        val png = byteArrayOf(0x89.toByte(), 'P'.code.toByte(), 'N'.code.toByte(), 'G'.code.toByte())
        val zip = ByteArrayOutputStream().also { out ->
            ZipOutputStream(out).use { z ->
                z.putNextEntry(ZipEntry("3D/3dmodel.model")); z.write("<model/>".toByteArray()); z.closeEntry()
                z.putNextEntry(ZipEntry("Metadata/slice_info.config")); z.write(xml.toByteArray()); z.closeEntry()
                z.putNextEntry(ZipEntry("Metadata/plate_1_small.png")); z.write(byteArrayOf(0)); z.closeEntry()
                z.putNextEntry(ZipEntry("Metadata/plate_1.png")); z.write(png); z.closeEntry()
            }
        }.toByteArray()

        val info = SliceParser.parse(ByteArrayInputStream(zip))
        assertEquals(5400L, info.printSeconds)
        assertEquals(2, info.plates)
        val black = info.filaments.first { it.colorHex == "#000000" }
        assertEquals(BigDecimal("36.3"), black.grams)
        assertArrayEquals(png, info.thumbnail)
    }

    @Test(expected = NotSlicedException::class)
    fun `un 3MF sin laminar se rechaza`() {
        val zip = ByteArrayOutputStream().also { out ->
            ZipOutputStream(out).use { z ->
                z.putNextEntry(ZipEntry("3D/3dmodel.model")); z.write("<model/>".toByteArray()); z.closeEntry()
            }
        }.toByteArray()
        SliceParser.parse(ByteArrayInputStream(zip))
    }

    @Test
    fun `lee el resumen al final de un G-code grande`() {
        val body = StringBuilder()
        repeat(200_000) { body.append("G1 X1.000 Y2.000 E0.0100\n") } // ~5 MB
        body.append("; filament used [g] = 42.0\n; estimated printing time (normal mode) = 3h 0m 0s\n")
        val info = SliceParser.parse(ByteArrayInputStream(body.toString().toByteArray()))
        assertEquals(10800L, info.printSeconds)
        assertEquals(BigDecimal("42.0"), info.filaments.single().grams)
    }
}
